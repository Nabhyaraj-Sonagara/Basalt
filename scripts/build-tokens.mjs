// Generates packages/ui/src/generated/tokens.css from the design system's tokens.json.
// Both themes are emitted: Comb (light, default) and Basalt (dark), switched with
// data-theme on <html>. "auto" follows the OS preference.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ds = join(root, 'design-system/project');
const out = join(root, 'packages/ui/src/generated');
const tokens = JSON.parse(readFileSync(join(ds, 'tokens.json'), 'utf8'));

const themed = { comb: [], basalt: [] };
const flat = [];

const resolveAlias = (v) => (typeof v === 'string' && /^\{[\w-]+\}$/.test(v) ? `var(--${v.slice(1, -1)})` : v);

function add(name, value) {
  if (value && typeof value === 'object') {
    themed.comb.push(`  --${name}: ${resolveAlias(value.comb)};`);
    themed.basalt.push(`  --${name}: ${resolveAlias(value.basalt)};`);
  } else {
    flat.push(`  --${name}: ${resolveAlias(value)};`);
  }
}

for (const t of tokens.color.tokens) add(t.name, t.value);
for (const group of ['spacing', 'radius', 'shape', 'shadow', 'timing']) {
  for (const t of tokens[group].tokens) add(t.name, t.value);
}
for (const [fam, stack] of Object.entries(tokens.type.families)) add(`font-${fam}`, stack);
for (const g of tokens.type.groups) {
  for (const s of g.styles) {
    add(`type-${s.name}`, `${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-${g.family})`);
    if (s.letterSpacing) add(`type-${s.name}-tracking`, s.letterSpacing);
  }
}

// Fonts are copied next to the CSS so Vite can bundle them.
mkdirSync(join(out, 'fonts'), { recursive: true });
for (const f of readdirSync(join(ds, 'fonts'))) copyFileSync(join(ds, 'fonts', f), join(out, 'fonts', f));
const faces = tokens.type.fonts.map(
  (f) => `@font-face { font-family: "${f.family}"; src: url("./${f.file}") format("woff2"); font-weight: ${f.weight}; font-style: ${f.style}; font-display: swap; }`,
);

const css = `/* Generated by scripts/build-tokens.mjs from design-system/project/tokens.json. Do not edit. */
${faces.join('\n')}

:root {
${flat.join('\n')}
}

:root, :root[data-theme="comb"] {
  color-scheme: light;
${themed.comb.join('\n')}
}

:root[data-theme="basalt"] {
  color-scheme: dark;
${themed.basalt.join('\n')}
}

@media (prefers-color-scheme: dark) {
  :root[data-theme="auto"] {
    color-scheme: dark;
${themed.basalt.map((l) => '  ' + l).join('\n')}
  }
}
`;
writeFileSync(join(out, 'tokens.css'), css);

// The component bundle and its CSS are copied so the app has no path into design-system/ at runtime.
copyFileSync(join(ds, 'components/bundle.js'), join(out, 'bundle.js'));
copyFileSync(join(ds, 'components/bundle.css'), join(out, 'bundle.css'));
mkdirSync(join(out, 'assets'), { recursive: true });
for (const f of readdirSync(join(ds, 'assets/Logos'))) {
  if (f.endsWith('.svg')) copyFileSync(join(ds, 'assets/Logos', f), join(out, 'assets', f));
}
console.log(`tokens.css: ${flat.length} global, ${themed.comb.length} themed tokens`);
